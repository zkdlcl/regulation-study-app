def _norm(v):
    return re.sub(r'\s+', '', v)


def _blank(quote, subs):
    out = html.escape(quote, quote=False)
    for s in subs:
        e = html.escape(s, quote=False)
        i = out.find(e)
        while i >= 0 and out.rfind('[[', 0, i) > out.rfind(']]', 0, i):   # 이미 빈칸 안이면 다음 것
            i = out.find(e, i + 1)
        if i < 0:
            raise ValueError(f'주체 낱말 없음: {s} / {quote}')
        out = out[:i] + '[[' + e + ']]' + out[i + len(e):]
    return out


def subject_table(law, arts):
    trs = []
    for label, no, quote, subs, note in SUBJ[law]:
        a = arts.get(f'{law}:{no}')
        if not a or _norm(quote) not in _norm(a['text']):
            raise ValueError(f'주체 표 원문 불일치: {law} 제{no}조 / {quote}')
        cell = '“' + _blank(quote, subs) + '”'
        if note:
            cell += f'<br><small class="mute">{html.escape(note, quote=False)}</small>'
        trs.append(f'<tr><td>제{label}</td><td>{cell}</td></tr>')
    n = SUBJ_NO[law]
    return (f'<h3>{n}. {SUBJ_TITLE[law]}</h3>\n<p class="mute small">원문 그대로, 주체만 가렸습니다. 회장·기관장·소속기관장·위원회를 바꿔 끼우는 함정이 많습니다.</p>\n'
            '<div class="tw blankable"><table>\n<tr><th>조문</th><th>원문</th></tr>\n' + '\n'.join(trs) + '\n</table></div>\n')


